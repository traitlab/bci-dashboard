#!/usr/bin/env bash
# Tar data/thumbs/480 and create or update the thumbs-480 release that the Pages workflow downloads.
# Run after labelling/fetch_photo_thumbs.py. Needs an authenticated gh.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SRC="$REPO/data/thumbs/480"
[ -n "$(ls -A "$SRC" 2>/dev/null)" ] || { echo "publish_thumbs: $SRC is missing or empty" >&2; exit 1; }

TAR="$(mktemp -d)/thumbs-480.tar"
tar -cf "$TAR" -C "$SRC" .
if gh release view thumbs-480 >/dev/null 2>&1; then
  gh release upload thumbs-480 "$TAR" --clobber
else
  gh release create thumbs-480 "$TAR" --title "Photo thumbnails (480px WebP)" \
    --notes "Generated by labelling/fetch_photo_thumbs.py. Extracted to thumbs/480/ by the Pages workflow."
fi
